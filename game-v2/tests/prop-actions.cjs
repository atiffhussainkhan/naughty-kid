const assert=require('node:assert/strict');
const THREE=require('../vendor/three/build/three.min.js');
global.THREE=THREE;
THREE.GLTFLoader=class {load(url,done){const scene=new THREE.Group();scene.add(new THREE.Mesh(new THREE.BoxGeometry(.1,.1,.1)));done({scene});}};
require('../js/props.js');
(async()=>{
 const scene=new THREE.Scene();
 const teacher=new THREE.Group();teacher.name='teacher';teacher.position.set(1,0,-5);scene.add(teacher);
 const pupil=new THREE.Group();pupil.name='kid-kid-1';pupil.position.set(0,0,3);scene.add(pupil);
 const loaded=await CLASSROOM.props.load(scene,{});
 CLASSROOM.props.syncVisuals({},scene,.05);
 const home=loaded.items.prize.position.clone();
 const state={phase:'B',kids:[{id:'kid-1'}],prizeClaimed:true,noteOnBack:true,plushOnMat:true,phaseB:{mailbox:true,glassesHolder:'kid-1'},beat:10};
 for(let i=0;i<100;i++)CLASSROOM.props.syncVisuals(state,scene,.05);
 assert.ok(loaded.items.prize.position.distanceTo(new THREE.Vector3(.3,.85,3.12))<.001,'prize follows pupil');
 assert.ok(loaded.items['sticky-note'].position.distanceTo(new THREE.Vector3(1,1.05,-5.22))<.001,'note attaches to teacher');
 assert.ok(loaded.items.plush.position.distanceTo(loaded.items['shield-mat'].position.clone().add(new THREE.Vector3(0,.15,0)))<.001,'throw settles on mat');
 assert.equal(scene.getObjectByName('classroom-confetti'),undefined,'no celebration before finale');
 state.finals={a:true};
 CLASSROOM.props.syncVisuals(state,scene,.05);
 const burst=scene.getObjectByName('classroom-confetti');
 assert.ok(burst && burst.children.length>0,'finale renders confetti');
 for(let i=0;i<200;i++)CLASSROOM.props.syncVisuals(state,scene,.05);
 assert.equal(scene.children.filter(c=>c.name==='classroom-confetti').length,1,'one burst per round');
 assert.ok(burst.children.every(p=>p.position.y>=.035),'confetti stays above floor');
 CLASSROOM.props.syncVisuals({},scene,.05);
 assert.equal(scene.getObjectByName('classroom-confetti'),undefined,'replay removes burst');
 assert.ok(loaded.items.prize.position.distanceTo(home)<.001,'replay restores prop');
 const drawingState={phase:'B',beat:8,round:1,kids:[{id:'kid-1'}],phaseB:{picture:null,doodleWindowOpen:false,landings:[]}};
 CLASSROOM.props.syncVisuals(drawingState,scene,.05);
 assert.equal(scene.getObjectByName('classroom-flashlight-drawing'),undefined,'closed window has no invented projection');
 drawingState.phaseB.doodleWindowOpen=true;
 CLASSROOM.props.syncVisuals(drawingState,scene,.05);
 let drawing=scene.getObjectByName('classroom-flashlight-drawing');
 assert.ok(drawing.visible && drawing.getObjectByName('flashlight-beam').visible,'open window lights the actual beam geometry');
 assert.equal(drawing.getObjectByName('flashlight-hat-crown'),undefined,'opening the window does not invent a drawing');
 drawingState.beat=9;drawingState.phaseB.picture='hat';drawingState.phaseB.doodleWindowOpen=false;
 let snapshot=JSON.stringify(drawingState);
 CLASSROOM.props.syncVisuals(drawingState,scene,.05);
 drawing=scene.getObjectByName('classroom-flashlight-drawing');
 assert.ok(drawing.getObjectByName('flashlight-hat-crown').geometry.index.count>0,'hat is rendered with real tube geometry, not a label');
 assert.ok(drawing.getObjectByName('flashlight-hat-brim'),'hat has a separate brim');
 assert.equal(JSON.stringify(drawingState),snapshot,'rendering does not modify beat or drawing evidence');
 let oldDisposed=false;
 drawing.getObjectByName('flashlight-hat-crown').geometry.addEventListener('dispose',()=>{oldDisposed=true;});
 drawingState.phaseB.picture='ears';
 CLASSROOM.props.syncVisuals(drawingState,scene,.05);
 drawing=scene.getObjectByName('classroom-flashlight-drawing');
 assert.ok(drawing.getObjectByName('flashlight-ear-left')&&drawing.getObjectByName('flashlight-ear-right'),'giant ears have two projected outlines');
 assert.equal(drawing.getObjectByName('flashlight-hat-crown'),undefined,'changing drawing removes old shape');
 assert.ok(oldDisposed,'replacing the drawing disposes its geometry');
 drawingState.phaseB.picture=null;
 CLASSROOM.props.syncVisuals(drawingState,scene,.05);
 assert.equal(drawing.visible,false,'quiet pause clears the light drawing');
 const finale={phase:'B',beat:10,round:1,kids:[{id:'kid-1'}],phaseB:{mailbox:true,picture:null,landings:[]}};
 CLASSROOM.props.syncVisuals(finale,scene,.05);
 assert.equal(scene.getObjectByName('classroom-silly-string'),undefined,'mailbox arrival alone does not fabricate a spray');
 finale.phaseB.landings.push({target:'desk',gentle:true,dance:false});
 snapshot=JSON.stringify(finale);
 CLASSROOM.props.syncVisuals(finale,scene,.05);
 let string=scene.getObjectByName('classroom-silly-string');
 assert.equal(string.userData.landings,1);
 assert.equal(string.getObjectByName('string-deposit-0').userData.target,'desk');
 assert.ok(string.getObjectByName('landed-string-0').geometry.index.count>0,'string is a visible strand mesh');
 assert.ok(string.getObjectByName('silly-string-spray').visible,'new spray has a visible stream');
 assert.equal(JSON.stringify(finale),snapshot,'spray without dance remains an uncompleted finale');
 for(let i=0;i<30;i++)CLASSROOM.props.syncVisuals(finale,scene,.05);
 assert.equal(string.getObjectByName('silly-string-spray').visible,false,'spray stream ends');
 assert.ok(string.getObjectByName('string-deposit-0').visible,'landed string stays on the target');
 finale.phaseB.landings.push({target:'shoes',gentle:true,dance:true});
 CLASSROOM.props.syncVisuals(finale,scene,.05);
 string=scene.getObjectByName('classroom-silly-string');
 assert.equal(string.getObjectByName('string-deposit-1').userData.target,'shoes','recorded shoes target has its own landing');
 assert.ok(string.getObjectByName('string-deposit-1').position.distanceTo(new THREE.Vector3(1,.11,-4.82))<1e-6,'shoes effect is attached to teacher feet, not desk');
 assert.equal(scene.children.filter(o=>o.name==='classroom-silly-string').length,1,'additional sprays replace the bounded effect rather than duplicate it');
 CLASSROOM.props.syncVisuals({phase:'A',beat:1,round:2,kids:[{id:'kid-1'}]},scene,.05);
 assert.equal(scene.getObjectByName('classroom-silly-string'),undefined,'round change cleans string even if setup was not rendered');
 assert.equal(scene.getObjectByName('classroom-flashlight-drawing'),undefined,'round change cleans light geometry');
 finale.round=2;finale.phaseB.landings=[{target:'desk',gentle:true,dance:true}];
 CLASSROOM.props.syncVisuals(finale,scene,.05);
 assert.ok(scene.getObjectByName('classroom-silly-string').getObjectByName('silly-string-spray').visible,'new round can replay the spray');
 CLASSROOM.props.syncVisuals({},scene,.05);
 assert.equal(scene.getObjectByName('classroom-silly-string'),undefined,'setup reset removes all string geometry');
 console.log('PASS: carried props, projected hat/ears, beam gating, recorded target-specific spray, settled string, immutable outcomes and replay cleanup');
})().catch(e=>{console.error(e);process.exitCode=1;});
